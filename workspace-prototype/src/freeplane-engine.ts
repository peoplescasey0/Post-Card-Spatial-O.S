/**
 * Freeplane (.mm) Mind Map & Outliner Engine for Post Card Spatial OS
 * Compatible with Freeplane, FreeMind, and OPML 2.0.
 */

export type FreeplaneNode = {
  id: string;
  text: string;
  folded?: boolean;
  position?: "left" | "right";
  color?: string;
  bgColor?: string;
  style?: "bubble" | "fork" | "as_parent";
  formula?: string; // e.g. "=3+4"
  icons?: string[];
  link?: string;
  details?: string;
  note?: string;
  children?: FreeplaneNode[];
};

function escapeXml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function renderFreeplaneNodeXml(node: FreeplaneNode, indent: number): string {
  const pad = "  ".repeat(indent);
  const textAttr = `TEXT="${escapeXml(node.text)}"`;
  const idAttr = `ID="${escapeXml(node.id)}"`;
  const posAttr = node.position ? ` POSITION="${node.position}"` : "";
  const foldedAttr = node.folded ? ` FOLDED="true"` : "";
  const colorAttr = node.color ? ` COLOR="${node.color}"` : "";
  const linkAttr = node.link ? ` LINK="${escapeXml(node.link)}"` : "";

  let inner = "";

  // Node Core Styling (Bubble, Colors)
  if (node.style === "bubble" || node.bgColor) {
    const bg = node.bgColor ? ` BACKGROUND_COLOR="${node.bgColor}"` : "";
    inner += `${pad}  <edge STYLE="sharp_bezier" />\n`;
    inner += `${pad}  <node STYLE="bubble"${bg} />\n`;
  }

  // Icons
  if (node.icons && node.icons.length > 0) {
    for (const icon of node.icons) {
      inner += `${pad}  <icon BUILTIN="${escapeXml(icon)}" />\n`;
    }
  }

  // Node Details (Text details, Formulas)
  if (node.formula) {
    inner += `${pad}  <detail><richcontent TYPE="DETAILS"><html><head></head><body><p><b>Calc:</b> ${escapeXml(node.formula)}</p></body></html></richcontent></detail>\n`;
  } else if (node.details) {
    inner += `${pad}  <detail><richcontent TYPE="DETAILS"><html><head></head><body><p>${escapeXml(node.details)}</p></body></html></richcontent></detail>\n`;
  }

  // Children
  if (node.children && node.children.length > 0) {
    for (const child of node.children) {
      inner += renderFreeplaneNodeXml(child, indent + 1);
    }
  }

  if (inner) {
    return `${pad}<node ${idAttr} ${textAttr}${posAttr}${foldedAttr}${colorAttr}${linkAttr}>\n${inner}${pad}</node>\n`;
  }

  return `${pad}<node ${idAttr} ${textAttr}${posAttr}${foldedAttr}${colorAttr}${linkAttr} />\n`;
}

/**
 * Serializes a Freeplane root node tree into an official Freeplane (.mm) XML document.
 */
export function stringifyFreeplaneMap(root: FreeplaneNode): string {
  let xml = `<map version="freeplane 1.11.0">\n`;
  xml += `<!-- Generated by Post Card Spatial OS - The One AI Butler -->\n`;
  xml += renderFreeplaneNodeXml(root, 1);
  xml += `</map>\n`;
  return xml;
}

